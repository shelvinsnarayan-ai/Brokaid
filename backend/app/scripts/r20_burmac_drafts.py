"""R2.0 — load BurMac's DRAFT compliance templates into its library and export DOCX + PDF for the owner.

    cd /app/backend && python -m app.scripts.r20_burmac_drafts [--out /app/docs/compliance_drafts/burmac]
Drafts only: nothing is made live, nothing counts for go-live until a Principal approves each document.
"""
from __future__ import annotations

import argparse
import asyncio
from pathlib import Path

from dotenv import load_dotenv

load_dotenv(Path(__file__).resolve().parents[2] / ".env")

from app.db import mongo as mongo_db  # noqa: E402
from app.kernel import compliance_library as lib  # noqa: E402


async def main(out: Path) -> None:
    await mongo_db.init_mongo_client()
    store = mongo_db.get_db_sync()
    t = await store.tenants.find_one({"slug": "burmac"})  # tenant-safe: system-only — resolve the BurMac tenant
    if not t:
        raise SystemExit("No burmac tenant in this database.")
    tid = t["tenant_id"]
    made = await lib.generate_drafts(store, tid, by="system", role="r20-drafts")
    print("created drafts:", [m["kind"] for m in made] or "none (already present)")
    out.mkdir(parents=True, exist_ok=True)
    for r in await lib.listing(store, tid):
        if r.get("insurer_issued"):
            continue
        for fmt in ("docx", "pdf"):
            data, _, name = await lib.download(store, tid, r["doc_id"], fmt)
            (out / name).write_bytes(data)
    (out / "README.txt").write_text(
        "DRAFT compliance templates for BurMac generated by brokAId (R2.0).\n"
        "Every [PLACEHOLDER] must be completed and each document reviewed by BurMac's licensee/compliance adviser.\n"
        "They are not legal advice and must not be given to clients until a Principal approves them in brokAId\n"
        "(Governance -> Compliance -> Library) and makes them live. PDS and TMD are insurer-issued: obtain them from each insurer.\n")
    print("wrote", sorted(p.name for p in out.iterdir()))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[3] / "docs" / "compliance_drafts" / "burmac"))
    asyncio.run(main(Path(ap.parse_args().out)))
